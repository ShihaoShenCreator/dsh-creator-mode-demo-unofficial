/**
 * Build step: inline the plain-JS modules into the single client.js the Harness
 * Web page loads through window.__ModuleLoader__.
 *
 * The three source modules are ES modules with `export` declarations. This
 * script strips the `export` keyword and concatenates them inside the factory
 * closure of src/client-src.js at their markers, so the shipped bundle needs
 * no bundler, no import map, and no network.
 *
 * Usage: node build.mjs            write client.js
 *        node build.mjs --check    verify client.js matches the sources
 */
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const INLINE = [
  { marker: 'engine', file: 'src/engine.js' },
  { marker: 'render3d', file: 'src/render3d.js' },
  { marker: 'scene', file: 'src/scene.js' },
]

/** Remove `export ` / `export const` prefixes so the code stays in one scope. */
function stripExports(source) {
  return source
    .replace(/^export\s+const\s+/gm, 'const ')
    .replace(/^export\s+function\s+/gm, 'function ')
    .replace(/^export\s+class\s+/gm, 'class ')
}

function indentBlock(source) {
  return source
    .split('\n')
    .map((line) => (line.length > 0 ? '    ' + line : line))
    .join('\n')
}

const shell = await readFile(join(here, 'src', 'client-src.js'), 'utf8')
const modules = []
for (const entry of INLINE) {
  const source = await readFile(join(here, entry.file), 'utf8')
  modules.push({ marker: entry.marker, code: indentBlock(stripExports(source).trimEnd()) })
}

let output = shell
for (const entry of modules) {
  const open = `    // #region inlined:${entry.marker}`
  const close = `    // #endregion inlined:${entry.marker}`
  const start = output.indexOf(open)
  const finish = output.indexOf(close)
  if (start === -1 || finish === -1 || start > finish) {
    throw new Error(`inlined region markers not found for ${entry.marker}`)
  }
  output = output.slice(0, start + open.length) + '\n' + entry.code + '\n' + output.slice(finish)
}

const header = `/* Transformer 3D lab \u2014 generated by build.mjs; edit src/client-src.js and src/*.js instead. */\n`
output = header + output + '\n'

const check = process.argv.includes('--check')
const target = join(here, 'client.js')
if (check) {
  const existing = await readFile(target, 'utf8').catch(() => '')
  if (existing !== output) {
    console.error('client.js is out of date; run: node build.mjs')
    process.exit(1)
  }
  console.log('client.js matches src/')
} else {
  await writeFile(target, output)
  console.log(`wrote client.js (${output.length} bytes)`)
}
